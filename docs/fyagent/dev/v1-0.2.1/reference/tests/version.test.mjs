import assert from "node:assert/strict";
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { spawnSync } from "node:child_process";
import test from "node:test";
import { fileURLToPath } from "node:url";

const currentDir = path.dirname(fileURLToPath(import.meta.url));
const referenceScript = path.resolve(currentDir, "..", "scripts", "version.mjs");

function createFixture({ withInstallerActions = true } = {}) {
  const root = fs.mkdtempSync(path.join(os.tmpdir(), "fyagent-version-test-"));
  fs.mkdirSync(path.join(root, "scripts"), { recursive: true });
  fs.mkdirSync(path.join(root, "src-tauri"), { recursive: true });
  fs.copyFileSync(referenceScript, path.join(root, "scripts", "version.mjs"));

  fs.writeFileSync(
    path.join(root, "package.json"),
    `${JSON.stringify(
      {
        name: "fyagent",
        private: true,
        scripts: {
          "version:get": "node scripts/version.mjs get",
          "version:check": "node scripts/version.mjs check",
          "version:set": "node scripts/version.mjs set",
          "version:bump": "node scripts/version.mjs bump",
        },
      },
      null,
      2,
    )}\n`,
  );
  fs.writeFileSync(
    path.join(root, "src-tauri", "tauri.conf.json"),
    '{"productName":"FyAgent","identifier":"com.fyagent.desktop"}\n',
  );
  fs.writeFileSync(
    path.join(root, "src-tauri", "Cargo.toml"),
    `[workspace]\nmembers = ["."${withInstallerActions ? ', "installer-actions"' : ""}]\nresolver = "2"\n\n[workspace.package]\nversion = "0.2.0"\n\n[package]\nname = "fyagent"\nversion.workspace = true\nedition = "2021"\n`,
  );

  if (withInstallerActions) {
    fs.mkdirSync(path.join(root, "src-tauri", "installer-actions"), {
      recursive: true,
    });
    fs.writeFileSync(
      path.join(root, "src-tauri", "installer-actions", "Cargo.toml"),
      '[package]\nname = "fyagent-installer-actions"\nversion.workspace = true\nedition = "2021"\npublish = false\n',
    );
  }

  const helperBlock = withInstallerActions
    ? '\n[[package]]\nname = "fyagent-installer-actions"\nversion = "0.2.0"\n'
    : "";
  fs.writeFileSync(
    path.join(root, "src-tauri", "Cargo.lock"),
    `# This file is automatically @generated by Cargo.\nversion = 4\n\n[[package]]\nname = "dependency-a"\nversion = "0.2.0"\n\n[[package]]\nname = "fyagent"\nversion = "0.2.0"\n${helperBlock}\n[[package]]\nname = "dependency-b"\nversion = "0.2.0"\n`,
  );

  return root;
}

function run(root, ...args) {
  return spawnSync(process.execPath, ["scripts/version.mjs", ...args], {
    cwd: root,
    encoding: "utf8",
  });
}

test("set updates the canonical version and local lock entries only", (t) => {
  const root = createFixture();
  t.after(() => fs.rmSync(root, { recursive: true, force: true }));

  const result = run(root, "set", "0.2.1");
  assert.equal(result.status, 0, result.stderr);
  assert.match(
    fs.readFileSync(path.join(root, "src-tauri", "Cargo.toml"), "utf8"),
    /\[workspace\.package\][\s\S]*version = "0\.2\.1"/,
  );

  const lock = fs.readFileSync(path.join(root, "src-tauri", "Cargo.lock"), "utf8");
  assert.match(lock, /name = "fyagent"\nversion = "0\.2\.1"/);
  assert.match(
    lock,
    /name = "fyagent-installer-actions"\nversion = "0\.2\.1"/,
  );
  assert.equal((lock.match(/name = "dependency-[ab]"\nversion = "0\.2\.0"/g) ?? []).length, 2);
});

test("check enforces exact tag equality", (t) => {
  const root = createFixture();
  t.after(() => fs.rmSync(root, { recursive: true, force: true }));

  assert.equal(run(root, "check", "--tag", "v0.2.0").status, 0);
  const mismatch = run(root, "check", "--tag", "v0.2.1");
  assert.equal(mismatch.status, 1);
  assert.match(mismatch.stderr, /release tag must be v0\.2\.0/);
});

test("set rejects prerelease and v-prefixed values", (t) => {
  const root = createFixture({ withInstallerActions: false });
  t.after(() => fs.rmSync(root, { recursive: true, force: true }));

  for (const invalid of ["v0.2.1", "0.2.1-beta.1", "0.2.1+build.2"] ) {
    const result = run(root, "set", invalid);
    assert.equal(result.status, 1, `${invalid}: ${result.stderr}`);
    assert.match(result.stderr, /stable SemVer X\.Y\.Z/);
  }
});

test("dry-run does not modify files", (t) => {
  const root = createFixture();
  t.after(() => fs.rmSync(root, { recursive: true, force: true }));
  const cargoPath = path.join(root, "src-tauri", "Cargo.toml");
  const before = fs.readFileSync(cargoPath, "utf8");

  const result = run(root, "set", "0.2.1", "--dry-run");
  assert.equal(result.status, 0, result.stderr);
  assert.equal(fs.readFileSync(cargoPath, "utf8"), before);
  assert.match(result.stdout, /would update src-tauri\/Cargo\.toml/);
});

test("get prints only the canonical application version", (t) => {
  const root = createFixture();
  t.after(() => fs.rmSync(root, { recursive: true, force: true }));

  const result = run(root, "get");
  assert.equal(result.status, 0, result.stderr);
  assert.equal(result.stdout, "0.2.0\n");
});

test("bump implements stable SemVer arithmetic", (t) => {
  const cases = [
    ["patch", "0.2.1"],
    ["minor", "0.3.0"],
    ["major", "1.0.0"],
  ];

  for (const [kind, expected] of cases) {
    const root = createFixture();
    t.after(() => fs.rmSync(root, { recursive: true, force: true }));
    const result = run(root, "bump", kind);
    assert.equal(result.status, 0, `${kind}: ${result.stderr}`);
    const getResult = run(root, "get");
    assert.equal(getResult.status, 0, getResult.stderr);
    assert.equal(getResult.stdout.trim(), expected);
  }
});

test("set enforces Windows Installer numeric limits", (t) => {
  const root = createFixture({ withInstallerActions: false });
  t.after(() => fs.rmSync(root, { recursive: true, force: true }));

  for (const invalid of ["256.0.0", "0.256.0", "0.0.65536"]) {
    const result = run(root, "set", invalid);
    assert.equal(result.status, 1, `${invalid}: ${result.stderr}`);
    assert.match(result.stderr, /ProductVersion limits/);
  }
});

test("check rejects reintroduced duplicate application version fields", (t) => {
  const root = createFixture();
  t.after(() => fs.rmSync(root, { recursive: true, force: true }));

  const packagePath = path.join(root, "package.json");
  const packageJson = JSON.parse(fs.readFileSync(packagePath, "utf8"));
  packageJson.version = "0.2.0";
  fs.writeFileSync(packagePath, `${JSON.stringify(packageJson, null, 2)}\n`);

  const tauriPath = path.join(root, "src-tauri", "tauri.conf.json");
  fs.writeFileSync(
    tauriPath,
    '{"productName":"FyAgent","version":"0.2.0","identifier":"com.fyagent.desktop"}\n',
  );

  const result = run(root, "check");
  assert.equal(result.status, 1);
  assert.match(result.stderr, /package\.json must not declare/);
  assert.match(result.stderr, /tauri\.conf\.json must omit version/);
});
